-- Used by: area_terrain.lua.
--[=[
BEGINNER WALKTHROUGH: area_tiles_data.lua

Each [area ID] block is a LIST of image-piece records {key,x,z,w,h}.
key is the PNG basename under resources/area_tiles; x/z is its lower map-world corner;
w/h is coverage in world tiles, NOT PNG pixel dimensions. key="a_753_0_0" resolves the
resource Plugin.resources.area_tiles.a_753_0_0 and a_753_0_0.png. Overview keys use o_753.

Example reuse:
  local pieces = require('area_tiles_data')[753] or {}
  for _, piece in ipairs(pieces) do print(piece.key, piece.x, piece.z, piece.w, piece.h) end
area_terrain.lua projects the top-left using x/z+h, culls pieces, and sizes them at scale.
main.lua chooses the area and provides the viewport geometry.

Cross-file connections:
  No require dependencies inside this file.
  Required directly by: area_terrain.lua.

require normally caches a module after the first load. A data module returns values;
a helper module returns functions/state constructors. See CODE_GUIDE.md for the full flow.
]=]

