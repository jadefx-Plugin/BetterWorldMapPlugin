--[=[
BEGINNER WALKTHROUGH: teleport_extra_data.lua

This reference catalogue adds missing teleport families to teleport_data.lua.
categories creates checkboxes under the Teleports heading (map_key.lua group 6).
points is a list of destination-area markers; it never invokes gameplay actions.

Each block represents one item/outfit/familiar destination. x/z are DISPLAY map
tiles, areaID selects the native map (28 is surface), category matches a filter,
itemID requests that item's real inventory artwork, and record defines its hover.
custom=true keeps these entries out of native marker-index lookups. Coordinates
are area references: a labelled access marker is not the actual interior landing.
Do not feed projected/display coordinates through worldToSurface a second time.

To reuse: require('teleport_extra_data').points returns these ordinary Lua records.
To extend: add a category if needed, then a point with the same schema. Confirm
the map, destination and icon separately; don't give dynamic destinations a fake
fixed location. TELEPORT_COVERAGE.md explains variable/unmapped destinations.

Source identities: local native item-name export. Destination cross-checks:
https://runescape.wiki/w/Teleportation and the item/outfit pages named in source.
No inventory, bank, equipment, unlock or network queries run from this module.
]=]

