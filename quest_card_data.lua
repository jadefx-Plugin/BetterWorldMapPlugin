--[=[
BEGINNER WALKTHROUGH: quest_card_data.lua

Each [QUEST config ID] block is cached presentation for ONE quest, not a surface pin.
name/description/difficulty/length are fallback text; icon is a native sprite ID;
members is membership; quests lists prerequisite quest IDs; skills lists
{skill=<native skill ID>,level=<required level>}. Numeric quest key 0 can be valid.

Example reuse:
  for id, quest in pairs(require('quest_card_data')) do print(id, quest.name, quest.length) end
quest_card.lua joins with a pin's row.questID and prefers config.Quest live checks.
quest_hover_assets separately maps skill IDs to icon sprites. Cached requirements are
not proof of the current player's completion or access.

Cross-file connections:
  No require dependencies inside this file.
  Required directly by: quest_card.lua.

require normally caches a module after the first load. A data module returns values;
a helper module returns functions/state constructors. See CODE_GUIDE.md for the full flow.
]=]

