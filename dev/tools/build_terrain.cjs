const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
const sharp = require(process.env.BWM_SHARP_MODULE || 'sharp');

// Original BWM atlas builder. Inputs are already-exported local game images.
// This tool does not download tiles or use another plugin's map implementation.
async function build(project) {
  const input = path.join(project, 'resources', 'surface_chunks');
  const out = path.join(project, 'resources', 'own_terrain');
  await fs.mkdir(out, {recursive:true});
  const entries = [];
  for (const name of (await fs.readdir(input)).sort()) {
    const m = /^c_(-?\d+)_(-?\d+)\.png$/.exec(name);
    if (!m) continue;
    const file = path.join(input,name);
    const bytes = await fs.readFile(file);
    const meta = await sharp(bytes).metadata();
    if (meta.width !== 1024 || meta.height !== 1024) throw Error(`Unexpected base tile size: ${name}`);
    entries.push({key:name.slice(0,-4),x:+m[1],z:+m[2],file,
      sha256:crypto.createHash('sha256').update(bytes).digest('hex')});
  }
  if (!entries.length) throw Error('No local surface_chunks images found');
  const levels=[{name:'detail',span:256,density:4,group:'surface_chunks',
    tiles:entries.map(e=>({key:e.key,x:e.x*256,z:e.z*256}))}];
  for (const factor of [2,4,8]) {
    const groups=new Map();
    for (const tile of entries) {
      const gx=Math.floor(tile.x/factor), gz=Math.floor(tile.z/factor), key=`${gx}:${gz}`;
      if (!groups.has(key)) groups.set(key,{gx,gz,tiles:[]});
      groups.get(key).tiles.push(tile);
    }
    const level={name:`overview${factor}`,span:256*factor,density:4/factor,group:'own_terrain',tiles:[]};
    const size=1024/factor;
    for (const group of groups.values()) {
      const overlays=[];
      for (const tile of group.tiles) {
        overlays.push({input:await sharp(tile.file).resize(size,size,{kernel:'lanczos3'}).png().toBuffer(),
          left:(tile.x-group.gx*factor)*size,
          top:(factor-1-(tile.z-group.gz*factor))*size});
      }
      const key=`lod${factor}_${group.gx}_${group.gz}`;
      await sharp({create:{width:1024,height:1024,channels:4,background:'#60769a'}})
        .composite(overlays).png().toFile(path.join(out,key+'.png'));
      level.tiles.push({key,x:group.gx*level.span,z:group.gz*level.span});
    }
    levels.push(level);
  }
  const quote=s=>JSON.stringify(s);
  let lua='-- Generated by our original tools/build_terrain.cjs from local BWM terrain exports.\nreturn {version=1,levels={\n';
  for (const level of levels) {
    lua+=`{name=${quote(level.name)},span=${level.span},density=${level.density},group=${quote(level.group)},tiles={\n`;
    for (const t of level.tiles) lua+=`{key=${quote(t.key)},x=${t.x},z=${t.z}},\n`;
    lua+='}},\n';
  }
  lua+='}}\n';
  await fs.writeFile(path.join(project,'data/maps/terrain_atlas.lua'),lua,'utf8');
  await fs.writeFile(path.join(project,'dev','audits','terrain_build.json'),JSON.stringify({
    generator:'Better World Map original atlas builder v1',
    inputs:'Existing local BWM terrain exports; no ClueTrainer/PrettyMap/RuneApps tiles imported',
    inputFiles:entries.map(({key,sha256})=>({key,sha256})),
    levels:levels.map(({name,span,density,tiles})=>({name,span,density,count:tiles.length}))
  },null,2)+'\n','utf8');
  return levels.map(l=>({name:l.name,tiles:l.tiles.length,span:l.span}));
}
module.exports={build};
if (require.main===module) build(path.resolve(process.argv[2]||path.join(__dirname,'../..')))
  .then(result=>process.stdout.write(JSON.stringify(result)+'\n'))
  .catch(error=>{process.stderr.write(error.stack+'\n');process.exitCode=1;});
