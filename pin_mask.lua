local M = {}
local function sample(x, y)
    if x < 0 or y < 0 or x >= 21 or y >= 27 then
        return 0, 0
    end
    local p = pixels[y + 1][x + 1]
    local a = p % 256
    return math.floor(p / 256) * a / 255, a
end
-- Bilinear sampling uses premultiplied colour so transparent pixels do not
-- introduce black fringes. Native pixel centers are unchanged at 100% size.
function M.Build(size, rgb, opacity)
    local w, h = math.floor(21 * size + 0.5), math.floor(27 * size + 0.5)
    local r, g, b =
        math.floor(rgb / 16777216) % 256, math.floor(rgb / 65536) % 256, math.floor(rgb / 256) % 256
    local runs = {}
    for y = 0, h - 1 do
        local start, last
        local function flush(x)
            if last and last % 256 > 0 then
                runs[#runs + 1] = { start, y, x - start, 1, last }
            end
        end
        for x = 0, w do
            local colour = 0
            if x < w then
                local sx, sy = (x + 0.5) * 21 / w - 0.5, (y + 0.5) * 27 / h - 0.5
                local ix, iy = math.floor(sx), math.floor(sy)
                local fx, fy = sx - ix, sy - iy
                local shade, alpha = 0, 0
                for dy = 0, 1 do
                    for dx = 0, 1 do
                        local lum, a = sample(ix + dx, iy + dy)
                        local weight = (dx == 0 and 1 - fx or fx) * (dy == 0 and 1 - fy or fy)
                        shade = shade + lum * weight
                        alpha = alpha + a * weight
                    end
                end
                if alpha > 0 then
                    local light = shade / alpha
                    colour = math.floor(r * light + 0.5) * 16777216
                        + math.floor(g * light + 0.5) * 65536
                        + math.floor(b * light + 0.5) * 256
                        + math.floor(alpha * opacity + 0.5)
                end
            end
            if colour ~= last then
                flush(x)
                start, last = x, colour
            end
        end
    end
    return runs, math.floor(10 * size + 0.5), math.floor(24 * size + 0.5)
end
return M
